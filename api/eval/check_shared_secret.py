"""Check the live shared-secret gate without printing it or writing a row.

Reads api/.env or the terminal's exported HUDDLE_SHARED_SECRET. The call-event
handler looks up bookingId before inserting anything; the probe ID below cannot
be generated by Huddle's b_<uuid> booking ID allocator and must be rejected.
"""

import os
from pathlib import Path
import sys

import httpx
from dotenv import load_dotenv

BASE = "https://maincloud.spacetimedb.com/v1/database/huddle-calhacks/route"
PROBE = {"bookingId": "huddle-auth-probe-not-a-booking", "type": "ended"}


def verify(client: httpx.Client, secret: str | None) -> tuple[bool, str]:
    missing = client.post(BASE + "/call-event", json=PROBE)
    if missing.status_code != 401:
        return False, f"Cannot confirm secret gate: no-secret request returned HTTP {missing.status_code}, expected 401."
    if not secret:
        return False, "Backend is reachable and rejects missing credentials (401). HUDDLE_SHARED_SECRET is not configured in this process or api/.env."
    authenticated = client.post(BASE + "/call-event", json=PROBE, headers={"X-Huddle-Secret": secret})
    if authenticated.status_code == 400:
        try:
            error = authenticated.json().get("error", "")
        except ValueError:
            error = ""
        if "unknown booking" in error and PROBE["bookingId"] in error:
            return True, "PASS: live backend accepted the shared secret and rejected the nonexistent booking. No booking or event was created."
    if authenticated.status_code == 401:
        return False, "FAIL: live backend rejected the shared secret (401). Ask Eric to confirm the deployed HUDDLE_SHARED_SECRET."
    return False, f"Could not confirm authentication: protected probe returned HTTP {authenticated.status_code}."


def main() -> int:
    load_dotenv(Path(__file__).resolve().parents[1] / ".env", override=False, interpolate=False)
    try:
        with httpx.Client(timeout=10, follow_redirects=False) as client:
            ok, message = verify(client, os.getenv("HUDDLE_SHARED_SECRET"))
    except httpx.HTTPError:
        print("Could not reach the live backend; no credential values were printed.")
        return 1
    print(message)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
